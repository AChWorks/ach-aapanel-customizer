"""Opt-in native-site abusive-scan bans through installed Fail2ban.

Nginx sensitive-path Guard handles requests before PHP. This separate
integration uses only the selected site's native combined access log and
known suspicious 403/404 requests; bans are enforced by the system firewall
for every site sharing the origin. It never installs Fail2ban, edits vendor
Nginx source, silently enables a jail or bans a peer's access log.

A root-owned recovery journal is durable before a Fail2ban configuration
change. A changed/foreign file is not overwritten or removed.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import stat
import subprocess
from uuid import uuid4

from ach_customizer_nginx_security import _site_identity, _source_safe
from ach_customizer_status_inspect import VHOST_ROOT
from ach_customizer_state import _open_state_dir

FILTER_DIR = Path("/etc/fail2ban/filter.d")
JAIL_DIR = Path("/etc/fail2ban/jail.d")
LOG_DIR = Path("/www/wwwlogs")
SOURCE_DIR = Path(VHOST_ROOT)
FILTER_NAME = "ach-customizer-scanner.conf"
SCHEMA = 1
MODE = "native_site_abusive_scan_fail2ban"
RULESET = "sensitive-scan-combined-v1"
MAX_FILE = 8192
_SHA = re.compile(r"[0-9a-f]{64}\Z")
_TOKEN = re.compile(r"[0-9a-f]{32}\Z")
_LOG = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*[.]log\Z")
_PARAMS = ("maxretry", "findtime", "bantime")
DEFAULTS = {"maxretry": 6, "findtime": 120, "bantime": 600}

# Match only high-confidence discovery or executable-upload attempts.
# All regexes are anchored to the client's actual address in Nginx's native
# combined access log; unrelated 404s, OAuth, ACME and .well-known are ignored.
# Supported request protocol tokens: HTTP/1.0, 1.1, 2, 2.0, 3, 3.0.
HEAD = r'^<HOST>\s+\S+\s+\S+\s+\[\]\s+"(?:GET|HEAD|POST|PUT|PATCH|DELETE|OPTIONS)\s+/'
TAIL = r'[^"\r\n]*\s+HTTP/(?:1[.]0|1[.]1|2(?:[.]0)?|3(?:[.]0)?)"\s+(?:403|404)\s+\d+'
FILTER_TEXT = (
    "# Generated by ACh aaPanel Customizer. Do not edit manually.\n"
    "[Definition]\n"
    "failregex = " + HEAD +
        r'(?:[^"\s]*/)?(?:[.]env(?:[.][^/"\s?]+)?|[.]git|[.]svn|[.]htaccess|[.]user[.]ini)(?:[/?]|(?=\s))' + TAIL + "\n"
    "            " + HEAD +
        r'(?:[^"\s]*/)?(?:backup|backups|db-backup|db_dump|db_dumps)/' + TAIL + "\n"
    "            " + HEAD +
        r'(?:[^"\s]*/)?(?:uploads|media|tmp)/[^"\s]*[.](?:php[0-9]?|phtml|phar)(?:[/?]|(?=\s))' + TAIL + "\n"
    "ignoreregex =\n"
)


class AbuseError(RuntimeError):
    def __init__(self, stage, message, recovery_id=None):
        super().__init__(message)
        self.stage, self.recovery_id = stage, recovery_id


def _hash(payload):
    return hashlib.sha256(payload).hexdigest()


def _name(site_id):
    if type(site_id) is not int or not 0 < site_id < 2147483648:
        raise AbuseError("identity", "Invalid native site")
    return "ach-customizer-scan-" + str(site_id)


def _journal_name(site_id):
    return "ach_customizer.abusive_scan." + str(site_id) + ".json"


def _directory(path):
    path = Path(path)
    if not path.is_absolute() or path.is_symlink():
        raise AbuseError("ownership", "Untrusted Fail2ban configuration directory")
    try:
        fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
        st = os.fstat(fd)
        if (not stat.S_ISDIR(st.st_mode) or st.st_uid != os.geteuid()
                or st.st_mode & 0o022):
            raise AbuseError("ownership", "Unsafe Fail2ban configuration ownership")
        return fd
    except Exception:
        if "fd" in locals():
            os.close(fd)
        raise


def _read(fd, name, *, limit=MAX_FILE):
    try:
        f = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=fd)
    except FileNotFoundError:
        return None
    try:
        info = os.fstat(f)
        if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid()
                or info.st_nlink != 1 or info.st_mode & 0o022
                or info.st_size > limit or info.st_size < 1):
            raise AbuseError("ownership", "Untrusted Fail2ban managed file")
        data = os.read(f, limit + 1)
        if len(data) != info.st_size:
            raise AbuseError("ownership", "Fail2ban managed file changed during inspection")
        return data
    finally:
        os.close(f)


def _create(fd, name, content, *, mode=0o644):
    f = os.open(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL |
                os.O_NOFOLLOW | os.O_CLOEXEC, mode, dir_fd=fd)
    try:
        os.fchmod(f, mode)
        os.write(f, content)
        os.fsync(f)
    finally:
        os.close(f)
    os.fsync(fd)


def _journal(fd, site_id):
    raw = _read(fd, _journal_name(site_id), limit=4096)
    if raw is None:
        return None
    try:
        row = json.loads(raw)
    except (ValueError, UnicodeError) as exc:
        raise AbuseError("recovery", "Unreadable scanner recovery journal") from exc
    if (not isinstance(row, dict)
            or set(row) != {"schema", "site_id", "site_key", "vhost_sha", "log_path",
                            "jail_sha", "filter_sha", "recovery_id", "phase", "policy"}
            or type(row["schema"]) is not int or row["schema"] != SCHEMA
            or type(row["site_id"]) is not int or row["site_id"] != site_id
            or not isinstance(row["site_key"], str)
            or not isinstance(row["vhost_sha"], str) or not _SHA.fullmatch(row["vhost_sha"])
            or not isinstance(row["log_path"], str)
            or Path(row["log_path"]).parent != LOG_DIR
            or not _LOG.fullmatch(Path(row["log_path"]).name)
            or not isinstance(row["jail_sha"], str) or not _SHA.fullmatch(row["jail_sha"])
            or row["filter_sha"] != _hash(FILTER_TEXT.encode())
            or not isinstance(row["recovery_id"], str) or not _TOKEN.fullmatch(row["recovery_id"])
            or row["phase"] not in ("prepared", "applied", "restored")
            or not isinstance(row["policy"], dict)
            or set(row["policy"]) != set(_PARAMS)
            or any(type(row["policy"][p]) is not int or row["policy"][p] <= 0
                   for p in _PARAMS)):
        raise AbuseError("recovery", "Invalid scanner recovery journal")
    return row


def _save(fd, site_id, row):
    data = (json.dumps(row, sort_keys=True, separators=(",", ":")) + "\n").encode()
    if len(data) > 4096:
        raise AbuseError("recovery", "Scanner recovery journal too large")
    name = _journal_name(site_id)
    temporary = ".ach_scan." + uuid4().hex + ".tmp"
    _create(fd, temporary, data, mode=0o600)
    try:
        os.replace(temporary, name, src_dir_fd=fd, dst_dir_fd=fd)
        os.fsync(fd)
    except Exception as exc:
        raise AbuseError("uncertain", "Scanner recovery journal commit uncertain") from exc


def _client(argv, *, runner=None):
    run = runner or subprocess.run
    try:
        result = run(["fail2ban-client", *argv], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise AbuseError("runtime", "Fail2ban client unavailable or timed out") from exc
    return result


def _running(jail, *, runner=None):
    result = _client(["status", jail], runner=runner)
    return result.returncode == 0 and ("Status for the jail:" in result.stdout)


def _policy(values):
    clean = {}
    for name in _PARAMS:
        value = values.get(name, DEFAULTS[name])
        if isinstance(value, str):
            if not re.fullmatch(r"[1-9][0-9]{0,9}", value):
                raise AbuseError("input", "Invalid Fail2ban numeric " + name)
            value = int(value)
        if type(value) is not int or not 0 < value < 2147483648:
            raise AbuseError("input", "Invalid Fail2ban numeric " + name)
        clean[name] = value
    return clean


def _site_log(site, *, vhost_root=SOURCE_DIR, log_dir=LOG_DIR):
    _site_identity(site)
    source_sha, _ = _source_safe(site, vhost_root=str(vhost_root),
                                 nginx_conf="/www/server/nginx/conf/nginx.conf")
    vhost = Path(vhost_root) / (site["name"] + ".conf")
    try:
        source = vhost.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        raise AbuseError("source", "Native VHost unavailable for Fail2ban") from exc
    # Only one native site-owned combined access log may drive the jail.
    # Accept the known aaPanel native directory but derive the file from
    # the actual selected site, never from a browser-supplied URL.
    log_dir = Path(log_dir)
    log_pattern = r"(?m)^\s*access_log\s+(" + re.escape(str(log_dir)) + r"/[A-Za-z0-9._-]+[.]log)\s*;"
    matches = set(re.findall(log_pattern, source))
    desired = str(log_dir / (site["name"] + ".log"))
    if matches != {desired} or not _LOG.fullmatch(Path(desired).name):
        raise AbuseError("source", "Selected site has no uniquely owned native combined access log")
    if (not log_dir.is_dir() or log_dir.is_symlink()
            or not Path(desired).is_file() or Path(desired).is_symlink()
            or Path(desired).resolve() != Path(desired)):
        raise AbuseError("source", "Selected site log path is missing or untrusted")
    log_stat, dir_stat = Path(desired).stat(), log_dir.stat()
    if (not stat.S_ISREG(log_stat.st_mode) or log_stat.st_nlink != 1
            or log_stat.st_mode & 0o002 or dir_stat.st_mode & 0o002):
        raise AbuseError("source", "Selected site log is not safely owned")
    return source_sha, desired


def _jail(site_id, log_path, policy):
    name = _name(site_id)
    # nftables filters both TCP (HTTP/1.1 + HTTP/2) and UDP (HTTP/3) on
    # standard web ports. Firewall bans apply to *all* virtual hosts on the
    # origin, not just the log source; operator-facing text must disclose it.
    lines = [
        "# Managed by ACh aaPanel Customizer. Disable via the native UI.",
        "[" + name + "]",
        "enabled = true",
        "filter = ach-customizer-scanner",
        "logpath = " + log_path,
        "backend = polling",
        "maxretry = " + str(policy["maxretry"]),
        "findtime = " + str(policy["findtime"]),
        "bantime = " + str(policy["bantime"]),
        # Fail2ban parses options as individual action definitions. A
        # protocol=tcp,udp value is invalid and fails before any jail starts;
        # create separate named nftables actions for each transport instead.
        "action = nftables[type=multiport, name=" + name + '-tcp' +
        ', port="80,443", protocol="tcp"]',
        "         nftables[type=multiport, name=" + name + '-udp' +
        ', port="80,443", protocol="udp"]',
        "",
    ]
    return "\n".join(lines).encode("ascii")


def manage(action, site, *, data_fd, params=None, expected_plan=None,
           recovery_id=None, approved=False, runner=None,
           filter_dir=FILTER_DIR, jail_dir=JAIL_DIR,
           vhost_root=SOURCE_DIR, log_dir=LOG_DIR):
    if action not in ("preview", "apply", "recheck", "restore"):
        raise AbuseError("input", "Unknown scanner protection operation")
    _site_identity(site)
    site_id = site["id"]
    jail = _name(site_id)
    stored = _journal(data_fd, site_id)
    filter_bytes = FILTER_TEXT.encode("ascii")
    if action in ("apply", "restore") and approved is not True:
        raise AbuseError("approval", "Explicit site selection and firewall authorization required")
    report = {
        "schema": SCHEMA, "mode": MODE, "ruleset": RULESET,
        "site_id": site_id, "site_key": site["name"],
        "state": "Unmanaged", "reason": "",
        "recovery_id": stored["recovery_id"] if stored else None,
        "journal_phase": stored["phase"] if stored else None,
        "runtime_verified": False, "changed": False,
        "read_only": action in ("preview", "recheck"),
        "firewall_scope": "origin_wide_web_ports",
        "log_scope": "selected_native_site",
    }
    policy = _policy(params or {})
    current = None
    filter_existing = None
    try:
        jail_fd = _directory(jail_dir)
        filter_fd = _directory(filter_dir)
        try:
            current = _read(jail_fd, jail + ".local")
            filter_existing = _read(filter_fd, FILTER_NAME)
        finally:
            os.close(jail_fd)
            os.close(filter_fd)
    except FileNotFoundError:
        if action in ("apply", "restore"):
            raise AbuseError("dependency", "Install/enable Fail2ban first")
        return {**report, "state": "Dependency Missing",
                "reason": "Fail2ban configuration directories unavailable"}
    if filter_existing not in (None, filter_bytes):
        raise AbuseError("ownership", "Foreign Fail2ban scanner filter exists")
    if action in ("preview", "recheck"):
        try:
            dep = _client(["-t"], runner=runner)
            if dep.returncode:
                return {**report, "state": "Dependency Missing",
                        "reason": "Fail2ban configuration invalid or binary unavailable",
                        "plan_sha256": None}
        except AbuseError:
            return {**report, "state": "Dependency Missing",
                    "reason": "Install and enable Fail2ban before scanner protection",
                    "plan_sha256": None}
        report["plan_sha256"] = None
        if stored and stored["site_key"] != site["name"]:
            state = "Needs Review"
        elif stored and stored["phase"] == "restored" and current is None:
            state = "Restored"
        elif stored and stored["phase"] in ("prepared", "applied"):
            if current == _jail(site_id, stored["log_path"], stored["policy"]):
                state = ("Applied" if filter_existing == filter_bytes
                         and _running(jail, runner=runner) else "Needs Review")
            else:
                state = "Recovery Required"
        elif current is not None:
            state = "Needs Review"
        else:
            state = "Unmanaged"
        try:
            vhost_sha, log = _site_log(site, vhost_root=vhost_root, log_dir=log_dir)
            if state == "Unmanaged" and site.get("status") not in ("1", 1):
                state = "Needs Review"
            if (stored and state == "Applied" and
                    (stored["vhost_sha"] != vhost_sha or stored["log_path"] != log)):
                state = "Needs Review"
            report.update(vhost_sha256=vhost_sha, log_path=log,
                          plan_sha256=_hash(_jail(site_id, log, policy) +
                                            filter_bytes + vhost_sha.encode()))
        except Exception as exc:
            report.update(vhost_sha256=None, log_path=None)
            if state in ("Unmanaged", "Applied"):
                state = "Needs Review"
        reason = {
            "Applied": "Selected site log is monitored; Fail2ban jail is running",
            "Restored": "Managed jail removed and recovery retained",
            "Unmanaged": "Selected native log ready; no scanner jail enabled",
            "Recovery Required": "Interrupted setup/restore; inspect recovery and retry removal",
            "Needs Review": "Native source, log or live Fail2ban jail needs attention",
        }.get(state, "Inspect Fail2ban")
        return {**report, "state": state, "reason": reason,
                "runtime_verified": (state == "Applied"
                                 or (state == "Restored"
                                     and not _running(jail, runner=runner))),
                "policy": stored["policy"] if stored else policy}

    if action == "apply":
        if site.get("status") not in ("1", 1):
            raise AbuseError("identity", "Cannot enable scan protection for stopped site")
        if current is not None or stored and stored["phase"] != "restored":
            raise AbuseError("recovery", "Existing scanner jail must be recovered first")
        vhost_sha, log_path = _site_log(site, vhost_root=vhost_root, log_dir=log_dir)
        jail_bytes = _jail(site_id, log_path, policy)
        plan = _hash(jail_bytes + filter_bytes + vhost_sha.encode())
        if expected_plan != plan:
            raise AbuseError("concurrency", "Scanner readiness changed; preview again")
        if _client(["-t"], runner=runner).returncode:
            raise AbuseError("runtime", "Existing Fail2ban configuration validation failed")
        if _site_log(site, vhost_root=vhost_root, log_dir=log_dir) != (vhost_sha, log_path):
            raise AbuseError("concurrency", "Native log/VHost changed since Fail2ban preview")
        new = {
            "schema": SCHEMA, "site_id": site_id, "site_key": site["name"],
            "vhost_sha": vhost_sha, "log_path": log_path,
            "jail_sha": _hash(jail_bytes), "filter_sha": _hash(filter_bytes),
            "recovery_id": uuid4().hex, "phase": "prepared", "policy": policy,
        }
        _save(data_fd, site_id, new)
        jail_fd, filter_fd = _directory(jail_dir), _directory(filter_dir)
        try:
            if filter_existing is None:
                _create(filter_fd, FILTER_NAME, filter_bytes)
            _create(jail_fd, jail + ".local", jail_bytes)
        finally:
            os.close(jail_fd)
            os.close(filter_fd)
        if _client(["-t"], runner=runner).returncode or _client(["reload"], runner=runner).returncode:
            raise AbuseError("uncertain", "Scanner files staged but Fail2ban reload unconfirmed; Restore by Recovery ID",
                             recovery_id=new["recovery_id"])
        if not _running(jail, runner=runner):
            raise AbuseError("uncertain", "Fail2ban jail did not start; Restore by Recovery ID",
                             recovery_id=new["recovery_id"])
        new["phase"] = "applied"
        _save(data_fd, site_id, new)
        return {**report, "state": "Applied", "reason": "Native site log and Fail2ban jail active",
                "recovery_id": new["recovery_id"], "journal_phase": "applied",
                "runtime_verified": True, "changed": True, "plan_sha256": plan,
                "vhost_sha256": vhost_sha, "log_path": log_path, "policy": policy}

    if not stored or stored["phase"] not in ("prepared", "applied") or recovery_id != stored["recovery_id"]:
        raise AbuseError("recovery", "Unknown or retired Fail2ban Recovery ID")
    desired = _jail(site_id, stored["log_path"], stored["policy"])
    if current not in (None, desired):
        raise AbuseError("recovery", "Fail2ban jail source changed; refusing foreign removal")
    jail_fd = _directory(jail_dir)
    try:
        if current is not None:
            os.unlink(jail + ".local", dir_fd=jail_fd)
            os.fsync(jail_fd)
    finally:
        os.close(jail_fd)
    if _client(["-t"], runner=runner).returncode or _client(["reload"], runner=runner).returncode:
        raise AbuseError("uncertain", "Fail2ban jail removal reload not confirmed; check Recovery ID",
                         recovery_id=stored["recovery_id"])
    if _running(jail, runner=runner):
        raise AbuseError("uncertain", "Fail2ban jail still running after removal; retry Restore",
                         recovery_id=stored["recovery_id"])
    stored["phase"] = "restored"
    _save(data_fd, site_id, stored)
    # Keep the small shared filter: another administrator-defined jail can
    # reference it, and its exact bytes are checked on every new Apply.
    # Cleanup removes only the proven site-owned jail.
    return {**report, "state": "Restored", "reason": "Exact owned jail stopped and retired",
            "recovery_id": stored["recovery_id"], "journal_phase": "restored",
            "runtime_verified": True, "changed": True,
            "vhost_sha256": stored["vhost_sha"], "log_path": stored["log_path"],
            "policy": stored["policy"]}


def plan(site, *, params=None, vhost_root=SOURCE_DIR, log_dir=LOG_DIR):
    vhost_sha, log_path = _site_log(site, vhost_root=vhost_root, log_dir=log_dir)
    policy = _policy(params or {})
    return _hash(_jail(site["id"], log_path, policy) +
                 FILTER_TEXT.encode("ascii") + vhost_sha.encode())
